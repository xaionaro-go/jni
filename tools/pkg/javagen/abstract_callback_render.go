package javagen

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// javaGeneratedHeader is prepended to all generated Java files.
var javaGeneratedHeaderLine = "// Code generated by javagen. DO NOT " + "EDIT."
var javaGeneratedHeader = javaGeneratedHeaderLine + "\n\n"

// renderAbstractAdapters generates a Java adapter class for each abstract
// callback. The Java files are placed in a java/ subdirectory alongside the
// Go output. Each generated package is rooted at center.dx.jni.generated and
// includes the adapted Java class package when one exists.
func renderAbstractAdapters(
	templatesDir string,
	merged *MergedSpec,
	pkgDir string,
	cleanStale bool,
) error {
	javaDir := filepath.Join(pkgDir, "java")
	if cleanStale {
		if err := cleanStaleJavaFiles(javaDir); err != nil {
			return fmt.Errorf("clean stale java files: %w", err)
		}
	}
	if len(merged.AbstractCallbacks) == 0 {
		return nil
	}

	tmplPath := filepath.Join(templatesDir, "abstract_adapter.java.tmpl")
	tmplData, err := os.ReadFile(tmplPath)
	if err != nil {
		return fmt.Errorf("read abstract adapter template %s: %w", tmplPath, err)
	}

	funcMap := template.FuncMap{
		"javaClassToSlash": JavaClassToSlash,
	}

	tmpl, err := template.New("abstract_adapter.java.tmpl").Funcs(funcMap).Parse(string(tmplData))
	if err != nil {
		return fmt.Errorf("parse abstract adapter template: %w", err)
	}

	if err := os.MkdirAll(javaDir, dirPerm); err != nil {
		return fmt.Errorf("mkdir java: %w", err)
	}

	for i := range merged.AbstractCallbacks {
		acb := &merged.AbstractCallbacks[i]
		outputFile := filepath.Join(javaDir, acb.AdapterClassName()+".java")
		if err := renderJavaTemplate(tmpl, acb, outputFile); err != nil {
			return fmt.Errorf("render adapter %s: %w", acb.GoType, err)
		}
	}

	return nil
}

// renderJavaTemplate executes a Java template and writes the result.
func renderJavaTemplate(
	tmpl *template.Template,
	data any,
	outputPath string,
) error {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}

	src := javaGeneratedHeader + buf.String()
	return os.WriteFile(outputPath, []byte(src), filePerm)
}

// cleanStaleJavaFiles removes generated .java files from a directory.
func cleanStaleJavaFiles(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("read java dir %s: %w", dir, err)
	}
	for _, e := range entries {
		if e.IsDir() || filepath.Ext(e.Name()) != ".java" {
			continue
		}
		path := filepath.Join(dir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read stale Java file %s: %w", path, err)
		}
		if !hasJavagenJavaHeader(data) {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("remove stale Java file %s: %w", path, err)
		}
	}
	return nil
}

func cleanIneligibleJavaAdapters(
	pkgDir string,
	eligibilities []AbstractCallbackEligibility,
) error {
	javaDir := filepath.Join(pkgDir, "java")
	for _, eligibility := range eligibilities {
		if eligibility.Generated || eligibility.JavaClass == "" {
			continue
		}
		path := filepath.Join(javaDir, javaSimpleName(eligibility.JavaClass)+"Adapter.java")
		data, err := os.ReadFile(path)
		if err != nil {
			if errors.Is(err, os.ErrNotExist) {
				continue
			}
			return fmt.Errorf("read ineligible Java adapter %s: %w", path, err)
		}
		if !hasJavagenJavaHeader(data) {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("remove ineligible Java adapter %s: %w", path, err)
		}
	}
	return nil
}

func javaSimpleName(javaClass string) string {
	if idx := strings.LastIndex(javaClass, "."); idx >= 0 {
		return javaClass[idx+1:]
	}
	return javaClass
}

func hasJavagenJavaHeader(data []byte) bool {
	firstLine, _, _ := bytes.Cut(data, []byte("\n"))
	firstLine = bytes.TrimSuffix(firstLine, []byte("\r"))
	return bytes.Equal(firstLine, []byte(javaGeneratedHeaderLine))
}
