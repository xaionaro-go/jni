func TestParseSimpleLine(t *testing.T) {
	got, err := Parse(strings.NewReader("int layout activity_main 0x7f0c0001\n"))
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	want := []Entry{{Type: "layout", Name: "activity_main", Hex: "0x7f0c0001"}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %+v, want %+v", got, want)
	}
}

func TestParseAllAcceptedTypes(t *testing.T) {
	// Cover every type in AcceptedTypes so adding/removing a type is caught
	// by this test instead of going unnoticed.
	var lines []string
	for typ := range AcceptedTypes {
		if typ == "styleable" {
			continue
		}
		lines = append(lines, "int "+typ+" sample 0x7f000001")
	}
	got, err := Parse(strings.NewReader(strings.Join(lines, "\n") + "\n"))
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	if len(got) != len(AcceptedTypes)-1 {
		t.Fatalf("expected %d entries, got %d", len(AcceptedTypes)-1, len(got))
	}
}

