func TestRoundTripRepresentativeRFile(t *testing.T) {
	rTxt, err := os.Open(filepath.Join("testdata", "material_smoke_representative_R.txt"))
	if err != nil {
		t.Fatalf("open representative R.txt fixture: %v", err)
	}
	defer func() { _ = rTxt.Close() }()

	entries, err := Parse(rTxt)
	if err != nil {
		t.Fatalf("Parse representative R.txt: %v", err)
	}
	if len(entries) == 0 {
		t.Fatalf("representative R.txt yielded zero entries")
	}

	var buf bytes.Buffer
	if err := Emit(entries, "rgen", "R_", &buf); err != nil {
		t.Fatalf("Emit representative R.txt: %v", err)
	}

	// Persist the generated file in a throwaway module and run go vet against
	// it. A standalone .go file with package rgen plus a go.mod alongside is
	// the minimum the toolchain needs.
	tmp := t.TempDir()
	if err := os.WriteFile(filepath.Join(tmp, "go.mod"), []byte("module rgentest\n\ngo 1.24\n"), 0o644); err != nil {
		t.Fatalf("write go.mod: %v", err)
	}
	if err := os.WriteFile(filepath.Join(tmp, "r_consts.go"), buf.Bytes(), 0o644); err != nil {
		t.Fatalf("write r_consts.go: %v", err)
	}

	cmd := exec.Command("go", "vet", "./...")
	cmd.Dir = tmp
	out, vetErr := cmd.CombinedOutput()
	if vetErr != nil {
		t.Fatalf("go vet on generated R.txt output failed: %v\n%s", vetErr, out)
	}
}

// mustContain fails the test unless every needle appears in haystack.
func mustContain(t *testing.T, haystack string, needles ...string) {
	t.Helper()
	for _, n := range needles {
		if !strings.Contains(haystack, n) {
			t.Fatalf("output missing %q\n--- output ---\n%s", n, haystack)
		}
	}
}

// mustOrder fails the test unless needles appear in the given order in
// haystack. Each needle must appear exactly once for unambiguous ordering.
func mustOrder(t *testing.T, haystack string, needles ...string) {
	t.Helper()
	last := -1
	for _, n := range needles {
		idx := strings.Index(haystack, n)
		if idx < 0 {
			t.Fatalf("needle %q not found", n)
		}
		if idx <= last {
			t.Fatalf("needle %q appears at %d but previous needle ended at %d (ordering broken)\n--- output ---\n%s", n, idx, last, haystack)
		}
		last = idx
	}
}
