func TestEmitSorted(t *testing.T) {
	entries := []Entry{
		{Type: "string", Name: "zeta", Hex: "0x7f100002"},
		{Type: "layout", Name: "main", Hex: "0x7f0c0001"},
		{Type: "string", Name: "alpha", Hex: "0x7f100001"},
		{Type: "color", Name: "primary", Hex: "0x7f060001"},
		{Type: "layout", Name: "activity_main", Hex: "0x7f0c0000"},
	}
	var buf bytes.Buffer
	if err := Emit(entries, "rgen", "R_", &buf); err != nil {
		t.Fatalf("Emit: %v", err)
	}
	out := buf.String()
	mustOrder(t, out,
		"R_layout_",
		"R_string_",
		"R_color_",
	)
	mustOrder(t, out, "R_layout_activity_main", "R_layout_main")
	mustOrder(t, out, "R_string_alpha", "R_string_zeta")
	if !strings.HasPrefix(out, "// Code generated by tools/cmd/r-consts. DO NOT EDIT.\n") {
		t.Fatalf("missing header; got %q", out[:80])
	}
	if !strings.Contains(out, "package rgen\n") {
		t.Fatalf("missing package declaration")
	}
}

func TestEmitDeterministic(t *testing.T) {
	entries := []Entry{
		{Type: "string", Name: "b", Hex: "0x2"},
		{Type: "layout", Name: "a", Hex: "0x1"},
		{Type: "styleable", Name: "Foo", IsArray: true, ArrayHexValues: []string{"0x1", "0x2"}},
		{Type: "styleable", Name: "Foo_attr1", Hex: "0"},
	}
	var first, second bytes.Buffer
	if err := Emit(entries, "rgen", "R_", &first); err != nil {
		t.Fatalf("Emit first: %v", err)
	}
	if err := Emit(entries, "rgen", "R_", &second); err != nil {
		t.Fatalf("Emit second: %v", err)
	}
	a := sha256.Sum256(first.Bytes())
	b := sha256.Sum256(second.Bytes())
	if a != b {
		t.Fatalf("two emit runs produced different output:\n--- first ---\n%s\n--- second ---\n%s", first.String(), second.String())
	}
}

func TestEmitStyleable(t *testing.T) {
	entries := []Entry{
		{Type: "styleable", Name: "AppBar", IsArray: true, ArrayHexValues: []string{"0x010100af", "0x7f040012"}},
		{Type: "styleable", Name: "AppBar_android_layout_height", Hex: "0"},
		{Type: "styleable", Name: "AppBar_layout_height", Hex: "1"},
	}
	var buf bytes.Buffer
	if err := Emit(entries, "rgen", "R_", &buf); err != nil {
		t.Fatalf("Emit: %v", err)
	}
	out := buf.String()
	mustContain(t, out,
		"var (",
		"R_styleable_AppBar = []int32{0x010100af, 0x7f040012}",
		"R_styleable_AppBar_android_layout_height int32 = 0",
		"R_styleable_AppBar_layout_height",
	)
	// gofmt aligns the columns of the index const block, so the literal `int32 =`
	// in the second const may be preceded by extra spaces. Search for the
	// constant name plus a separator that gofmt cannot collapse.
	mustOrder(t, out,
		"R_styleable_AppBar = []int32",
		"R_styleable_AppBar_layout_height ",
	)
}

func TestEmitSanitizesNames(t *testing.T) {
	// aapt2 already uses underscores, but a hand-crafted R.txt could carry
	// `.`, `:`, or `-` in a styleable attribute name; the emit step replaces
	// those so the output is valid Go.
	entries := []Entry{
		{Type: "styleable", Name: "AppBar", IsArray: true, ArrayHexValues: []string{"0x1"}},
		{Type: "styleable", Name: "AppBar_android.layout-height:foo", Hex: "0"},
	}
	var buf bytes.Buffer
	if err := Emit(entries, "rgen", "R_", &buf); err != nil {
		t.Fatalf("Emit: %v", err)
	}
	out := buf.String()
	mustContain(t, out, "R_styleable_AppBar_android_layout_height_foo int32 = 0")
	if strings.Contains(out, "AppBar_android.layout-height:foo") {
		t.Fatalf("sanitize did not run; raw special chars present in output")
	}
}

