package rconsts

import (
	"fmt"
	"go/format"
	"io"
	"sort"
	"strings"
)

// Emit writes a deterministic Go source file containing one constant per
// scalar entry and one []int32 var per styleable array, plus per-attribute
// index constants. Entries are grouped by sub-type in EmitOrder, then
// styleable arrays (sorted by name), then styleable index constants (sorted
// by name); within each group entries are sorted alphabetically by Name. The
// output is run through go/format so the result is gofmt-clean.
func Emit(entries []Entry, pkg, prefix string, w io.Writer) error {
	if pkg == "" {
		return fmt.Errorf("Emit: pkg is required")
	}
	if prefix == "" {
		return fmt.Errorf("Emit: prefix is required")
	}

	groups := groupByType(entries)

	var b strings.Builder
	b.WriteString("// Code generated by tools/cmd/r-consts. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	writeScalarGroups(&b, groups, prefix)
	writeStyleableArrays(&b, groups["styleable"], prefix)
	writeStyleableIndices(&b, groups["styleable"], prefix)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("gofmt generated source: %w", err)
	}
	if _, err := w.Write(formatted); err != nil {
		return fmt.Errorf("write output: %w", err)
	}
	return nil
}

// groupByType buckets entries into per-type slices. Each per-type slice is
// already sorted by name on return so callers do not need to sort again.
// Entries with an unrecognised type (which Parse would have rejected) are
// silently dropped here; this only matters for callers that synthesize
// Entry values without going through Parse.
func groupByType(entries []Entry) map[string][]Entry {
	groups := make(map[string][]Entry)
	for _, e := range entries {
		if _, ok := AcceptedTypes[e.Type]; !ok {
			continue
		}
		groups[e.Type] = append(groups[e.Type], e)
	}
	for t := range groups {
		sort.Slice(groups[t], func(i, j int) bool { return groups[t][i].Name < groups[t][j].Name })
	}
	return groups
}

func writeScalarGroups(b *strings.Builder, groups map[string][]Entry, prefix string) {
	for _, typ := range EmitOrder {
		entries := groups[typ]
		if len(entries) == 0 {
			continue
		}
		fmt.Fprintf(b, "// %s\nconst (\n", typ)
		for _, e := range entries {
			fmt.Fprintf(b, "\t%s%s_%s int32 = %s\n", prefix, typ, sanitize(e.Name), e.Hex)
		}
		b.WriteString(")\n\n")
	}
}

func writeStyleableArrays(b *strings.Builder, styleables []Entry, prefix string) {
	arrays := filterArrays(styleables)
	if len(arrays) == 0 {
		return
	}
	b.WriteString("// styleable arrays\nvar (\n")
	for _, e := range arrays {
		fmt.Fprintf(b, "\t%sstyleable_%s = []int32{", prefix, sanitize(e.Name))
		for i, v := range e.ArrayHexValues {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(v)
		}
		b.WriteString("}\n")
	}
	b.WriteString(")\n\n")
}

func writeStyleableIndices(b *strings.Builder, styleables []Entry, prefix string) {
	indices := filterIndices(styleables)
	if len(indices) == 0 {
		return
	}
	b.WriteString("// styleable attribute indices\nconst (\n")
	for _, e := range indices {
		fmt.Fprintf(b, "\t%sstyleable_%s int32 = %s\n", prefix, sanitize(e.Name), e.Hex)
	}
	b.WriteString(")\n")
}

func filterArrays(styleables []Entry) []Entry {
	var out []Entry
	for _, e := range styleables {
		if e.IsArray {
			out = append(out, e)
		}
	}
	return out
}

func filterIndices(styleables []Entry) []Entry {
	var out []Entry
	for _, e := range styleables {
		if !e.IsArray {
			out = append(out, e)
		}
	}
	return out
}

// sanitize replaces R.txt characters that are illegal in Go identifiers with
// underscores. Real aapt2 output already uses underscores everywhere, but
// the substitution is cheap insurance against hand-crafted R.txt files where
// `.`, `:`, or `-` appear in symbol names.
func sanitize(name string) string {
	r := strings.NewReplacer(".", "_", ":", "_", "-", "_")
	return r.Replace(name)
}
